export function searchByLabel(query: string): string[] {
  if (!query) return [];

  // Lower bound binary search to find the first possible match
  let low = 0;
  let high = SORTED_LABEL_LIST.length;
  while (low < high) {
    const mid = Math.floor((low + high) / 2);
    if (SORTED_LABEL_LIST[mid] < query) {
      low = mid + 1;
    } else {
      high = mid;
    }
  }

  const results: string[] = [];

  // Collect all items starting with the prefix
  for (let i = low; i < SORTED_LABEL_LIST.length; i += 1) {
    const item = SORTED_LABEL_LIST[i];
    if (item.startsWith(query)) results.push(item);
    else break; // stop when prefix no longer matches
  }

  return results;
}

export function fuzzySearchByLabel(query: string): string[] {
  if (!query) return [];

  return SORTED_LABEL_LIST.filter((label) => label.toLowerCase().includes(query.toLowerCase()));
}
