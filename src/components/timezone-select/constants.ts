const getFraction = (val: number): number => val - Math.floor(val);

// Accepts timezone and returns offset formatted as "GMT[+-]00:00"
const getGMTOffset = (timeZone: string) => {
  try {
    const offsetInMinutes = dayjs().tz(timeZone).utcOffset(); // returns offset * 60

    if (Number.isNaN(offsetInMinutes)) return '';

    const offset = offsetInMinutes / 60;

    if (offset === 0) return 'GMT';

    const flooredOffset = offset < 0 ? Math.ceil(offset) : Math.floor(offset);
    const fraction = Math.floor(getFraction(offset) * 60);

    return `GMT${flooredOffset > 0 ? '+' : '-'}${Math.abs(flooredOffset)
      .toString(10)
      .padStart(2, '0')}:${fraction.toString(10).padStart(2, '0')}`;
  } catch {
    return '';
  }
};

export const TIMEZONE_OFFSETS: Record<string, string> = Object.keys(TIMEZONE_LABELS).reduce(
  (prev, curr) => {
    prev[curr] = getGMTOffset(curr);

    return prev;
  },
  {} as Record<string, string>
);

